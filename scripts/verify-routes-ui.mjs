import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const routes = await readFile(new URL('../src/screens/MapScreen.tsx', import.meta.url), 'utf8');
const policy = await readFile(new URL('../src/features/routes/routeStartPolicy.ts', import.meta.url), 'utf8');
assert.match(routes, /showExamples = false/);
assert.match(routes, /const routes = showExamples \? draftRoutes : \[\]/);
assert.doesNotMatch(routes, /从设备地图开始规划巡航路线|以下是界面示例|生产控制与路线执行器未接入/);
assert.doesNotMatch(routes, /onStartRoute\s*\(/);
assert.match(routes, /ControlPanelMotion/);
assert.match(routes, /KeyboardAvoidingView/);
assert.match(routes, /getAdaptivePageLayout/);
assert.match(policy, /candidate\.source !== 'trusted'/);
assert.match(policy, /candidate\.geometryValidation !== 'validated'/);
console.log('Route presentation and command separation verified');
